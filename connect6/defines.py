# Value of a living set of stones, named by tier. SetWeight names the tiers —
# the four tunable ones read from the weights file, LIVE_FIVE pinned at 10000
# to keep the terminal scores and the completion-pair threshold exact;
# LIVE_WEIGHTS is what the search hot paths index by run length, holding plain
# ints — enum members in that table would slow down the inner loops.
class SetWeight(IntEnum):
    SINGLE = int(_WEIGHTS["single"])
    PAIR = int(_WEIGHTS["pair"])
    TRIPLE = int(_WEIGHTS["triple"])
    LIVE_FOUR = int(_WEIGHTS["four"])
    LIVE_FIVE = 10000


def weight_tables(data: dict[str, int]) -> tuple[tuple[int, ...], tuple[int, ...], int]:
    live = (
        0,
        int(data["single"]),
        int(data["pair"]),
        int(data["triple"]),
        int(data["four"]),
        int(SetWeight.LIVE_FIVE),
    )
    factor = (1, int(data["factor_two"]), int(data["factor_many"]))
    return live, factor, int(data["threat"])


_LIVE_TABLE, _FACTOR_TABLE, _THREAT_TABLE = weight_tables(_WEIGHTS)

LIVE_WEIGHTS: Final[tuple[int, ...]] = _LIVE_TABLE

# Space multiplier for living sets, indexed by min(free - (6 - length), 2):
# the number of extra completable 6-windows beyond the only one. A set that
# fits in exactly one window is worth the plain tier weight; two windows
# double it, three or more triple it. Live fives are excluded: one open end
# already wins next move, and no living set may reach the terminal scores.
WINDOW_FACTOR: Final[tuple[int, ...]] = _FACTOR_TABLE

# Threat vocabulary (thesis: a side has t threats iff the opponent must place
# t stones to stop it connecting six; the defender places two stones per turn,
# so three or more simultaneous threats win). THREAT_WIN is the sentinel a
# completed-6-window returns from the sliding window; 7 is unmistakable next
# to any real count. THREAT_WEIGHT prices one threat into the pair ranking:
# one forced defender stone is worth one live-4 tier of urgency.
THREAT_WIN: Final = 7
THREAT_WEIGHT: Final = _THREAT_TABLE
THREAT_RANK_WIDTH: Final = 10  # Pairs per node re-ranked by threat count (cost gate).

# Forward pruning for the quiescence search: candidate-pair widths by ply
# from the root — the full MAX_CANDIDATE_MOVES at the root and at the
# opponent's first reply ply (a refutation pruned there is a tactical
# blind spot the deeper plies cannot repair), narrower from the mover's
# own follow-up ply on, where nodes multiply and quiescence already
# covers the forcing continuations at the leaves. Completion pairs are
# always added before the width cut, so one-move wins and forced blocks
# survive every width.
FORWARD_WIDTHS: Final[tuple[int, ...]] = (30, 30, 16, 10)

# Quiescence: at the horizon the position is priced by standing pat on the
# static evaluation unless it is loud — the last move created threats, or a
# live five stands (a standing pat of magnitude >= LIVE_FIVE). Loud nodes
# expand their head candidates (the generator injects wins and blocks
# first); quiet nodes expand only pairs creating at least this many threats
# — the defender places two stones per turn, so two threats are exactly
# blockable and only three or more are truly forcing; the extension stops
# after QUIESCENCE_DEPTH plies. Threat counts exist only for completion
# pairs and the THREAT_RANK_WIDTH re-rank window — other pairs read as
# quiet.
QUIESCENCE_MIN_THREATS: Final = 3
QUIESCENCE_WIDTH: Final = 8
QUIESCENCE_DEPTH: Final = 6

# VCF — the forced-win search of the deployed engine (v5): a narrow
# recursion over forcing moves only. A threat window is a 6-window free of
# defender stones; a five-window (5 attacker stones, 1 empty) forces the
# defender to fill that exact empty, a four-window (4 stones, 2 empties)
# forces one stone into either empty. The defender places two stones per
# turn, so three or more uncovered windows lose at once, exactly two make
# the reply fully determined — the chain's only sound continuation — and
# one or fewer leaves the defender a free stone that can refute anything;
# such branches are discarded, so every reported win is proven. VCF_PLY_CAP
# bounds the chain length, VCF_NODE_CAP makes a pathological probe return
# inconclusive instead of hanging the move.
VCF_PLY_CAP: Final = 20
VCF_NODE_CAP: Final = 1500

# The v5 root: forced-win offense first, then the enhanced search deepened
# deterministically while the cumulative node count stays under
# V5_NODE_BUDGET (the budget is in nodes, not seconds, so reruns stay
# exact; the started iteration may overshoot, but the next one never
# starts), then a defense screen in two parts: the chosen move is
# discarded if it hands the opponent a proven forced win, and it is also
# discarded if it leaves the opponent an armed split pair — two of their
# stones with a two-cell gap whose one-move join would force our entire
# reply — falling back to the first screened root candidate (or a
# constructed gap-breaking pair) that does not. V5_DEEPEN_STEPS is the
# number of plies added to the floor depth (the protocol's depth
# command); V5_SCREEN_WIDTH bounds the probed candidates.
V5_NODE_BUDGET: Final = 12000
V5_DEEPEN_STEPS: Final = 2
V5_SCREEN_WIDTH: Final = 6

# Lightweight hot-path companions of Position/Move: plain tuples so that
